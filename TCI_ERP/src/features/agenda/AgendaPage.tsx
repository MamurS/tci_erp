/**
 * «Моя повестка» — the personal, cross-cutting queue: what do *I* owe right
 * now, whatever object it hangs off. Two views of the same board:
 *
 *  * List — one row per piece of work (board.ts merges and collapses),
 *    grouped by due date, company or family, filtered by chips kept in the
 *    URL; hover or keyboard focus reveals a row's actions.
 *  * Triage — a preview, not a workplace: the queue on the left, the selected
 *    task on the right with what is needed to understand it, and a primary
 *    button to the screen where it is DONE (destinations.ts). Nothing is
 *    decided, recalculated or edited here.
 *
 * Rows are generated by the database and close themselves when their object
 * moves on; snoozing and commenting are the only writes (migration 0055),
 * and marking done exists only for the four manual types.
 */

