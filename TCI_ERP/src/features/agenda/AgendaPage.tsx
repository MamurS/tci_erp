type View = 'list' | 'triage'

/** The view and the grouping are remembered per person, per browser. */
function useRemembered(userId: string | null) {
  const key = `tci-erp-agenda:${userId ?? 'anon'}`
  const read = (): { view: View; grouping: Grouping } => {
    try {
      const raw = JSON.parse(localStorage.getItem(key) ?? '{}') as { view?: string; grouping?: string }
      return {
        view: raw.view === 'triage' ? 'triage' : 'list',
        grouping: (GROUPINGS as readonly string[]).includes(raw.grouping ?? '') ? (raw.grouping as Grouping) : 'due',
      }
    } catch {
      return { view: 'list', grouping: 'due' }
    }
  }
  const [state, setState] = useState(read)
  const update = (next: Partial<{ view: View; grouping: Grouping }>) => {
    setState((current) => {
      const merged = { ...current, ...next }
      try {
        localStorage.setItem(key, JSON.stringify(merged))
      } catch {
        // storage blocked: the choice lasts for this visit only
      }
      return merged
    })
  }
  return [state, update] as const
}

function isTyping(target: EventTarget | null): boolean {
  const el = target as HTMLElement | null
  if (!el) return false
  return el.isContentEditable || ['INPUT', 'TEXTAREA', 'SELECT'].includes(el.tagName)
}

export function AgendaPage() {
  const { t, i18n } = useTranslation()
  const locale = i18n.language
  const navigate = useNavigate()
  const { session } = useAuth()
  const me = session?.user.id ?? null
  const [params, setParams] = useSearchParams()
  const filter = readFilter(params)
  const [{ view, grouping }, remember] = useRemembered(me)

  const tasksQuery = useAgendaTasks()
  const all = useMemo(() => tasksQuery.data ?? [], [tasksQuery.data])
  // One clock for the board, taken when the rows were fetched, so a task
  // cannot be overdue in its label and on time in its group.
  const now = useMemo(() => new Date(tasksQuery.dataUpdatedAt || Date.now()), [tasksQuery.dataUpdatedAt])

  const { data: subjects } = useTaskSubjects(all)
  const { data: staff } = useStaffDirectory()
  const { data: cleared } = useClearedToday()
  const complete = useCompleteTask()
  const unsnooze = useUnsnoozeTask()

  const currencies = useMemo(
    () => [...new Set(all.map((task) => amountOf(task)?.currency).filter((c): c is string => Boolean(c)))],
    [all],
  )
  const { data: rates } = useUzsRates(currencies)
  const rateFor = useCallback((ccy: string) => latestUzsRate(rates ?? [], ccy, todayIso()), [rates])

  // What the board shows: active (or snoozed) → mine → family.
  const active = useMemo(() => activeTasks(all, now), [all, now])
  const snoozed = useMemo(() => all.filter((task) => isSnoozed(task, now)), [all, now])
  const scope = filter.snoozed ? snoozed : active
  const mineScope = useMemo(() => scope.filter((task) => assignedToMe(task, me)), [scope, me])
  const familyScope = filter.mine ? mineScope : scope
  const visible = useMemo(
    () => (filter.family ? familyScope.filter((task) => TASK_FAMILY[task.task_type] === filter.family) : familyScope),
    [familyScope, filter.family],
  )
  const company = useCallback((row: AgendaRow) => companyOf(row.lead, subjects), [subjects])
  const groups = useMemo(() => buildBoard(visible, grouping, now, company), [visible, grouping, now, company])

  // The summary line reads the whole active board, whatever the filter.
  const summary = useMemo(() => {
    const board = buildBoard(active, 'due', now, () => null)
    const overdueRows = board.find((g) => g.key === 'overdue')?.rows ?? []
    return {
      overdue: active.filter((task) => isOverdue(task, now)).length,
      atStake: sumUzs(overdueRows, rateFor),
      // Today's desk: due today, plus undated urgent and high work (board.ts).
      dueToday: active.filter((task) => bucketOf(task, now) === 'today').length,
    }
  }, [active, now, rateFor])

  // Comments and origin text for the snippets.
  const { data: comments } = useTaskComments(visible.map((task) => task.id))
  const requestIds = useMemo(
    () => visible.filter((task) => task.object_type === 'credit_limit_request').map((task) => task.object_id),
    [visible],
  )
  const { data: justifications } = useLimitJustifications(requestIds)
  const validationIds = useMemo(
    () => visible.filter((task) => task.object_type === 'limit_validation').map((task) => task.object_id),
    [visible],
  )
  const { data: validationComments } = useValidationComments(validationIds)

  const snippetOf = useCallback(
    (row: AgendaRow): RowSnippet | null => {
      const ids = new Set(row.tasks.map((task) => task.id))
      const own = (comments ?? []).filter((c) => ids.has(c.task_id))
      const origin = [
        ...row.tasks.flatMap(paramComments).map((c) => c.body),
        ...(row.lead.object_type === 'credit_limit_request' && justifications?.get(row.lead.object_id)?.justification
          ? [justifications.get(row.lead.object_id)?.justification as string]
          : []),
        ...row.tasks.flatMap((task) => validationOrigin(task, validationComments)?.body ?? []),
      ]
      const count = own.length + origin.length
      const latest = own[own.length - 1]?.body ?? origin[origin.length - 1]
      if (latest) return { kind: 'comment', text: latest, count }
      // A collapsed row's note would describe only its first item.
      if (row.kind !== 'collapsed' && (isAutomatic(row.lead) || row.lead.task_type === 'limit_escalated')) {
        const note = systemNote(row.lead)
        if (note) return { kind: 'note', text: renderNote(note, t, locale, staff), count: 0 }
      }
      return null
    },
    [comments, justifications, validationComments, t, locale, staff],
  )

  // Interaction state.
  const [focusedKey, setFocusedKey] = useState<string | null>(null)
  const [commentingKey, setCommentingKey] = useState<string | null>(null)
  const [actionError, setActionError] = useState<string | null>(null)
  const [handled, setHandled] = useState<Map<string, number>>(new Map())
  const markHandled = useCallback((row: AgendaRow) => {
    setHandled((current) => new Map(current).set(row.key, Date.now()))
  }, [])

  const runComplete = async (row: AgendaRow) => {
    setActionError(null)
    try {
      // One call for the row: it leaves the board in the next frame.
      await complete.mutateAsync(row.tasks.filter((task) => canCompleteByHand(task.task_type)).map((task) => task.id))
      markHandled(row)
    } catch (error) {
      setActionError(t(refusalKey(error)))
    }
  }
  const runUnsnooze = async (row: AgendaRow) => {
    setActionError(null)
    try {
      await unsnooze.mutateAsync(row.tasks.filter((task) => task.snoozed_until).map((task) => task.id))
    } catch (error) {
      setActionError(t(refusalKey(error)))
    }
  }

  const setFilter = (next: BoardFilter) => setParams(writeFilter(params, next), { replace: true })
  const setView = (next: View) => remember({ view: next })

  // Keyboard: J/K move, Enter goes to the task screen, O opens the object,
  // C comments, E marks done (manual types only), S snoozes, T toggles.
  const rows = useMemo(() => groups.flatMap((g) => g.rows), [groups])
  const rowByKey = useMemo(() => new Map(rows.map((r) => [r.key, r])), [rows])
  const triageSelect = useRef<((delta: number) => void) | null>(null)
  useEffect(() => {
    const onKey = (e: KeyboardEvent) => {
      if (e.metaKey || e.ctrlKey || e.altKey || isTyping(e.target)) return
      if (document.querySelector('[role="dialog"], [role="menu"]')) return
      const key = e.key.toLowerCase()
      if (key === 't') {
        e.preventDefault()
        setView(view === 'list' ? 'triage' : 'list')
        return
      }
      if (view === 'triage') {
        if (key === 'j' || key === 'k') {
          e.preventDefault()
          triageSelect.current?.(key === 'j' ? 1 : -1)
        }
        return // the triage panel handles Enter, O, C, S itself
      }
      const links = [...document.querySelectorAll<HTMLElement>('[data-row-link]')]
      const at = links.findIndex((el) => el.dataset.rowLink === focusedKey)
      if (key === 'j' || key === 'k') {
        e.preventDefault()
        const next = links[Math.max(0, Math.min(links.length - 1, at + (key === 'j' ? 1 : -1)))] ?? links[0]
        next?.focus()
        return
      }
      const row = focusedKey ? rowByKey.get(focusedKey) : undefined
      if (!row) return
      if (e.key === 'Enter') {
        e.preventDefault()
        markHandled(row)
        navigate(destinationFor(row, { subject: companyOf(row.lead, subjects), reference: referenceOf(row.lead, subjects) }).path)
      } else if (key === 'o') {
        const href = taskLink({ ...row.lead, task_type: row.lead.task_type })
        if (href) navigate(href)
      } else if (key === 'c') {
        e.preventDefault()
        setCommentingKey(row.key)
      } else if (key === 'e' && row.tasks.some((task) => canCompleteByHand(task.task_type))) {
        void runComplete(row)
      } else if (key === 's') {
        e.preventDefault()
        document
          .querySelector<HTMLElement>(`[data-row-key="${CSS.escape(row.key)}"] [aria-haspopup="menu"]`)
          ?.click()
      }
    }
    window.addEventListener('keydown', onKey)
    return () => window.removeEventListener('keydown', onKey)
  })

  // ---------------------------------------------------------------------------

  const mineCount = active.filter((task) => assignedToMe(task, me)).length
  const families = familyCounts(filter.mine ? mineScope : scope)
  const filtered = Boolean(filter.family || filter.mine || filter.snoozed)

  const header = (
    <PageHeader
      title={t('agenda.title')}
      subtitle={
        tasksQuery.isLoading ? (
          <span aria-hidden className="inline-block h-4 w-80 animate-pulse rounded bg-slate-200" />
        ) : (
          <span className="text-slate-600 tabular-nums">
            {summary.overdue > 0 ? (
              <span className="font-semibold text-neg-600">{t('agenda.summary.overdue', { count: summary.overdue })}</span>
            ) : (
              t('agenda.summary.noneOverdue')
            )}
            {summary.atStake.uzs !== null &&
              ` · ${t('agenda.summary.atStake', { amount: formatCompact(summary.atStake.uzs, locale) })}`}
            {summary.atStake.missingRates > 0 &&
              ` (${t('agenda.groupMeta.noRate', { count: summary.atStake.missingRates })})`}
            {` · ${t('agenda.summary.dueToday', { count: summary.dueToday })}`}
            {cleared !== undefined && ` · ${t('agenda.summary.cleared', { count: cleared })}`}
          </span>
        )
      }
      actions={
        <>
          <Segmented
            tone="solid"
            ariaLabel={t('agenda.views.label')}
            value={view}
            onChange={(key) => setView(key as View)}
            options={[
              { key: 'list', label: t('agenda.views.list') },
              { key: 'triage', label: t('agenda.views.triage') },
            ]}
          />
          {view === 'list' && (
            <ActionsMenu
              label={t('agenda.groupBy.button', { value: t(`agenda.groupBy.${grouping}`) })}
              actions={GROUPINGS.map((g) => ({
                key: g,
                label: t(`agenda.groupBy.${g}`),
                onSelect: () => remember({ grouping: g }),
              }))}
            />
          )}
        </>
      }
    />
  )

  const chips = (
    <div className="mb-5 flex flex-wrap items-center gap-2" role="toolbar" aria-label={t('agenda.chips.label')}>
      <Chip
        active={!filter.family && !filter.mine}
        onClick={() => setFilter({ ...filter, family: null, mine: false })}
        label={t('common.all')}
        count={scope.length}
      />
      <Chip
        active={filter.mine}
        onClick={() => setFilter({ ...filter, mine: !filter.mine })}
        label={t('agenda.chips.mine')}
        count={filter.snoozed ? mineScope.length : mineCount}
      />
      <span aria-hidden className="mx-1 h-5 w-px bg-slate-200" />
      {FAMILIES.filter((f) => families.some((x) => x.family === f)).map((family) => (
        <Chip
          key={family}
          active={filter.family === family}
          onClick={() => setFilter({ ...filter, family: filter.family === family ? null : family })}
          label={t(`agenda.families.${family}`)}
          count={families.find((x) => x.family === family)?.count ?? 0}
        />
      ))}
      <span className="flex-1" />
      {(snoozed.length > 0 || filter.snoozed) && (
        <Chip
          dashed
          active={filter.snoozed}
          onClick={() => setFilter({ ...filter, snoozed: !filter.snoozed })}
          label={t('agenda.chips.snoozed')}
          count={snoozed.length}
        />
      )}
    </div>
  )

  let body: React.ReactNode
  if (tasksQuery.isLoading) {
    body = (
      <div className="overflow-hidden rounded-lg border border-slate-200 bg-white" aria-busy="true">
        {Array.from({ length: 6 }, (_, i) => (
          <div key={i} className="flex h-14 items-center gap-3 border-b border-slate-100 px-4 last:border-b-0">
            <Skeleton className="h-5 w-16" />
            <div className="flex-1 space-y-1.5">
              <Skeleton className="h-3.5 w-2/5" />
              <Skeleton className="h-3 w-3/5" />
            </div>
            <Skeleton className="h-4 w-14" />
            <Skeleton className="size-7 rounded-full" />
          </div>
        ))}
      </div>
    )
  } else if (tasksQuery.isError) {
    body = <Callout tone="neg" title={t('agenda.loadFailed')} />
  } else if (groups.length === 0) {
    body =
      !filtered && active.length === 0 && snoozed.length > 0 ? (
        <EmptyState title={t('agenda.empty.allSnoozed')} hint={t('agenda.empty.allSnoozedHint', { count: snoozed.length })} />
      ) : filtered ? (
        <EmptyState title={t('agenda.empty.filtered')} hint={t('agenda.empty.filteredHint')} />
      ) : (
        <EmptyState
          title={t('agenda.empty.title')}
          hint={t('agenda.empty.refreshed', { moment: formatMoment(now, locale) })}
        />
      )
  } else if (view === 'triage') {
    body = (
      <TriageView
        groups={groups}
        now={now}
        subjects={subjects}
        staff={staff}
        comments={comments ?? []}
        justifications={justifications}
        rateFor={rateFor}
        handled={handled}
        onHandled={markHandled}
        onError={setActionError}
        onComplete={(row) => void runComplete(row)}
        onUnsnooze={(row) => void runUnsnooze(row)}
        registerMove={(fn) => {
          triageSelect.current = fn
        }}
      />
    )
  } else {
    body = (
      <AgendaList
        groups={groups}
        ctx={{
          now,
          locale,
          subjects,
          staff,
          rateFor,
          snippetOf,
          focusedKey,
          onFocusRow: setFocusedKey,
          commentingKey,
          setCommentingKey,
          onComplete: (row) => void runComplete(row),
          onUnsnooze: (row) => void runUnsnooze(row),
          onError: setActionError,
          onHandled: markHandled,
        }}
      />
    )
  }

  return (
    <div>
      {header}
      {chips}
      {actionError && (
        <div className="mb-4">
          <Callout tone="neg" title={actionError} />
        </div>
      )}
      {body}
      {!tasksQuery.isLoading && groups.length > 0 && <KeyLegend view={view} />}
    </div>
  )
}

function Chip({
  label,
  count,
  active,
  onClick,
  dashed = false,
}: {
  label: string
  count: number
  active: boolean
  onClick: () => void
  dashed?: boolean
}) {
  return (
    <button
      type="button"
      aria-pressed={active}
      onClick={onClick}
      // The border is there in both states (navy when active), so pressing a
      // chip never changes its width and the chips beside it never move.
      className={`inline-flex h-8 items-center gap-1.5 rounded-full border px-3.5 text-[13px] font-medium transition-colors focus-visible:ring-2 focus-visible:ring-accent-400 focus-visible:ring-offset-1 focus-visible:outline-none ${
        active
          ? 'border-accent-600 bg-accent-600 text-white'
          : `bg-white text-slate-700 hover:border-slate-400 hover:text-slate-900 ${
              dashed ? 'border-dashed border-slate-400' : 'border-slate-300'
            }`
      }`}
    >
      {label}
      <span className={`inline-block min-w-[2ch] text-center tabular-nums ${active ? 'text-white' : 'text-slate-600'}`}>
        {count}
      </span>
    </button>
  )
}

function KeyLegend({ view }: { view: View }) {
  const { t } = useTranslation()
  const keys: [string[], string][] =
    view === 'list'
      ? [
          [['J', 'K'], t('agenda.keys.move')],
          [['Enter'], t('agenda.keys.go')],
          [['O'], t('agenda.keys.object')],
          [['C'], t('agenda.keys.comment')],
          [['E'], t('agenda.keys.done')],
          [['S'], t('agenda.keys.snooze')],
          [['T'], t('agenda.keys.triage')],
        ]
      : [
          [['J', 'K'], t('agenda.keys.move')],
          [['Enter'], t('agenda.keys.go')],
          [['O'], t('agenda.keys.object')],
          [['C'], t('agenda.keys.comment')],
          [['S'], t('agenda.keys.snooze')],
          [['T'], t('agenda.keys.list')],
        ]
  return (
    <div className="mt-6 flex flex-wrap items-center gap-x-5 gap-y-2 border-t border-slate-200 pt-4 text-[12.5px] text-slate-600">
      {keys.map(([kbd, label]) => (
        <span key={label} className="inline-flex items-center gap-1.5">
          {kbd.map((k) => (
            <kbd key={k} className="rounded border border-slate-300 bg-white px-1.5 py-px font-mono text-[11px] text-slate-700">
              {k}
            </kbd>
          ))}
          {label}
        </span>
      ))}
      <span className="ml-auto inline-flex items-center gap-1">{t('agenda.autoLegend')}</span>
    </div>
  )
}
