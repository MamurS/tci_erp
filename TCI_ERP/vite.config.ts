import { execSync } from 'node:child_process'
import fs from 'node:fs'
import path from 'node:path'

import { defineConfig } from 'vite'
import type { Plugin } from 'vite'
import react from '@vitejs/plugin-react'
import tailwindcss from '@tailwindcss/vite'

/**
 * The build's identity, so a tab left open across a deploy can tell that it
 * runs old code (src/lib/appVersion.ts). Cloudflare Pages gives the commit;
 * a local build asks git; `vite dev` is always "dev" and emits no file.
 */
function buildId(command: 'build' | 'serve'): string {
  if (command === 'serve') return 'dev'
  const fromPages = process.env.CF_PAGES_COMMIT_SHA
  if (fromPages) return fromPages
  try {
    return execSync('git rev-parse HEAD', { stdio: ['ignore', 'pipe', 'ignore'] }).toString().trim()
  } catch {
    return `local-${Date.now()}`
  }
}

/** Stamps the build id into the bundle (`__APP_BUILD__`) and next to it
 * (`/version.json`), which a running tab re-reads to compare. */
function appVersion(): Plugin {
  let id = 'dev'
  return {
    name: 'tci-app-version',
    config(_config, { command }) {
      id = buildId(command)
      return { define: { __APP_BUILD__: JSON.stringify(id) } }
    },
    generateBundle() {
      this.emitFile({ type: 'asset', fileName: 'version.json', source: JSON.stringify({ build: id }) })
    },
  }
}

/**
 * The user guide's screenshots and quick-start PDFs (docs/guide/shots,
 * docs/guide/pdf — committed once, generated by npm run guide:shots / guide:pdf)
 * are served at /guide/shots/… and /guide/pdf/…: from the folder in dev,
 * copied into the build. Same origin, so the CSP needs no change.
 */
function guideAssets(): Plugin {
  const dirs = {
    shots: path.resolve(import.meta.dirname, 'docs/guide/shots'),
    pdf: path.resolve(import.meta.dirname, 'docs/guide/pdf'),
  }
  let outDir = 'dist'
  return {
    name: 'tci-guide-assets',
    configResolved(config) {
      outDir = path.resolve(config.root, config.build.outDir)
    },
    configureServer(server) {
      server.middlewares.use((req, res, next) => {
        const m = /^\/guide\/(shots|pdf)\/([\w-]+)\/([\w.-]+\.(?:webp|pdf))$/.exec(decodeURIComponent((req.url ?? '').split('?')[0]))
        if (!m) return next()
        const file = path.join(dirs[m[1] as keyof typeof dirs], m[2], m[3])
        if (!fs.existsSync(file)) return next()
        res.setHeader('Content-Type', m[3].endsWith('.pdf') ? 'application/pdf' : 'image/webp')
        fs.createReadStream(file).pipe(res)
      })
    },
    closeBundle() {
      for (const [name, dir] of Object.entries(dirs)) {
        if (!fs.existsSync(dir)) continue
        fs.cpSync(dir, path.join(outDir, 'guide', name), { recursive: true, filter: (f) => !f.endsWith('.json') })
      }
    },
  }
}

// https://vite.dev/config/
export default defineConfig({
  plugins: [react(), tailwindcss(), appVersion(), guideAssets()],
  // The standard wording templates ship as .docx assets (src/features/wording/defaults).
  assetsInclude: ['**/*.docx'],
})
