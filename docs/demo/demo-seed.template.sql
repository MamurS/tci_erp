-- =====================================================================
-- TCI ERP — MVP demonstration dataset (reset + seed)
-- =====================================================================
--
-- What: wipes every BUSINESS row in schema tci and loads a coherent demo
--       book: policyholders and prospects, buyers in 12 countries with
--       three years of financials and real engine ratings, submissions at
--       every stage, policies, credit limits (approved / partial / declined
--       / escalated / held / adjusted / pending), corporate groups and a
--       group limit, declarations and premium, overdue notifications with
--       the automatic suspension, claims through to payment and recovery,
--       a client proposal, and the Agenda those events produce.
-- Why:  the owner asked for a clean database with demo data covering every
--       case, to show the MVP.
--
-- KEPT: every auth account that is not @demo.invalid, with its roles,
--       profile and authority grants; reference data (countries,
--       currencies, industries, fx rates, statement forms and IFRS
--       mappings, workflow settings, insurer particulars, uploaded contract
--       templates); the security tables (auth events, lockouts, attempts).
-- ADDED to reference data: UZS rates for the demo currencies (source
--       'manual', dated 2025-12-31) where none exists.
--
-- HOW:  run the whole file in the Supabase SQL editor of the canonical
--       project (ref reunqrpeumokqgarknge) — NEVER anywhere else. It is ONE
--       transaction: any failure rolls everything back and the database is
--       as it was. Re-running it is safe: it wipes and rebuilds the demo.
--       Generated by docs/demo/build_demo_seed.py; edit that, not this.
--
-- The workflow part runs as the demo users, through the same functions the
-- screens call (decide_limit_request, file_overdue_notification,
-- approve_claim, …), so histories, workflow events and Agenda tasks are the
-- real thing. Timestamps are then moved into the past (every UPDATE with a
-- WHERE) so the book has an age: ratings months old, reviews coming due,
-- overdue notifications 40–150 days past due.
-- =====================================================================

begin;

set local search_path = public, extensions;

-- ---------------------------------------------------------------------------
-- 1. Wipe. TRUNCATE without CASCADE: if a table outside this list ever
--    references one inside it, this fails instead of reaching further.
-- ---------------------------------------------------------------------------
truncate table
  tci.workflow_events, tci.tasks,
  tci.recoveries, tci.claim_payments, tci.claim_documents, tci.claim_invoice_verdicts,
  tci.claim_invoices, tci.claim_status_history, tci.claims,
  tci.overdue_notifications,
  tci.premium_entries, tci.declaration_lines, tci.declarations, tci.premium_instalments,
  tci.policy_documents, tci.policy_status_history,
  tci.decision_conditions, tci.credit_limit_decisions, tci.credit_limit_requests,
  tci.insurance_request_history, tci.insurance_request_buyers, tci.insurance_requests,
  tci.policies, tci.policyholder_users, tci.client_buyer_proposals,
  tci.group_limits, tci.entity_relationship_suggestions, tci.entity_relationships,
  tci.credit_assessments, tci.local_statement_values, tci.balance_sheets, tci.income_statements,
  tci.financial_statements, tci.legal_entities;

-- numbering starts again with the book (CL-YYYY-0001, IR-…)
alter sequence tci.claim_seq restart with 1;
alter sequence tci.insurance_request_seq restart with 1;

-- demo accounts from an earlier run (their roles, profiles and grants go with them)
delete from tci.authority_grants where user_id in (select id from auth.users where email like '%@demo.invalid');
delete from tci.user_roles       where user_id in (select id from auth.users where email like '%@demo.invalid');
delete from tci.user_profiles    where user_id in (select id from auth.users where email like '%@demo.invalid');
delete from auth.identities      where user_id in (select id from auth.users where email like '%@demo.invalid');
delete from auth.users           where email like '%@demo.invalid';

-- ---------------------------------------------------------------------------
-- 3. UZS rates for the demo currencies (reference data; kept on a rerun)
-- ---------------------------------------------------------------------------
insert into tci.fx_rates (currency_code, rate_to_uzs, rate_date, source)
select v.ccy, v.rate, date '2025-12-31', 'manual'
  from (values ('USD', 12025.33), ('EUR', 13071.01), ('RUB', 130.71), ('KZT', 23.58), ('TRY', 293.30),
               ('CNY', 1670.18), ('AED', 3276.66), ('KRW', 8.71), ('GBP', 15230.00),
               ('CHF', 13900.00), ('JPY', 80.50)) as v(ccy, rate)
 where not exists (select 1 from tci.fx_rates f where f.currency_code = v.ccy)
on conflict do nothing;

create temp table demo_keys (key text primary key, id uuid not null) on commit drop;

-- @@GENERATED@@

-- ---------------------------------------------------------------------------
-- 5. Helpers for the workflow part
-- ---------------------------------------------------------------------------
create function pg_temp.k(p_key text) returns uuid language sql stable as $$
  select id from demo_keys where key = p_key
$$;

-- Act as a demo user the way a REST call does: role authenticated, the JWT
-- claims, MFA satisfied, and no internal-call token left over from trusted
-- code that ran earlier in this transaction.
create function pg_temp.act(p_user text) returns void language plpgsql as $$
begin
  perform set_config('role', 'postgres', true);
  perform set_config('request.jwt.claims',
    jsonb_build_object('sub', pg_temp.k('user:' || p_user), 'role', 'authenticated', 'aal', 'aal2')::text, true);
  perform set_config('tci.internal_call', '', true);
  perform set_config('role', 'authenticated', true);
end $$;

create function pg_temp.owner() returns void language plpgsql as $$
begin
  perform set_config('role', 'postgres', true);
  perform set_config('request.jwt.claims', '', true);
end $$;

grant select on demo_keys to authenticated;
grant execute on function pg_temp.k(text) to authenticated;

-- @@WORKFLOW@@

select pg_temp.owner();

-- ---------------------------------------------------------------------------
-- 9. What was built
-- ---------------------------------------------------------------------------
do $$
declare v text;
begin
  select format('entities %s, statements %s, ratings %s, submissions %s, policies %s, limit requests %s, decisions %s, declarations %s, NOAs %s, claims %s, tasks open %s, demo users %s',
    (select count(*) from tci.legal_entities), (select count(*) from tci.financial_statements),
    (select count(*) from tci.credit_assessments), (select count(*) from tci.insurance_requests),
    (select count(*) from tci.policies), (select count(*) from tci.credit_limit_requests),
    (select count(*) from tci.credit_limit_decisions), (select count(*) from tci.declarations),
    (select count(*) from tci.overdue_notifications), (select count(*) from tci.claims),
    (select count(*) from tci.tasks where status = 'open'),
    (select count(*) from auth.users where email like '%@demo.invalid'))
    into v;
  raise notice 'demo seed: %', v;
  -- every case the demo relies on is present, or nothing is committed
  if (select count(*) from tci.policies where status = 'active') < 6
     or (select count(*) from tci.credit_limit_requests where status = 'escalated') < 1
     or (select count(*) from tci.credit_limit_decisions where held) < 1
     or (select count(*) from tci.credit_limit_decisions where stage = 'commercial') < 1
     or (select count(*) from tci.overdue_notifications where suspension_decision_id is not null) < 3
     or (select count(*) from tci.claims) <> 3
     or (select count(*) from tci.insurance_requests where status = 'bound') <> 1
     or (select count(distinct reason) from tci.v_rating_worklist) <> 4
     or (select count(*) from tci.group_limits) <> 1
     or (select count(*) from tci.client_buyer_proposals) <> 1
     or (select count(distinct task_type) from tci.tasks where status = 'open') < 15 then
    raise exception 'demo seed: a case is missing — nothing was committed';
  end if;
end $$;

commit;
